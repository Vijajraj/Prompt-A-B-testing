async def score_responses(
    query: str,
    prompt_a: str, response_a: str,
    prompt_b: str, response_b: str,
    prompt_c: str, response_c: str,
) -> tuple[list[dict], str]:
    """
    Score 3 responses using the configured scoring mode.

    Returns:
        (scores_list, scorer_used)
        scores_list: [{score, reason}, {score, reason}, {score, reason}]
        scorer_used: 'judge' or 'ml'
    """
    use_ml = False

    if SCORER_MODE == "ml":
        use_ml = True
    elif SCORER_MODE == "auto":
        use_ml = model_exists()
    # else: SCORER_MODE == "judge" → use_ml stays False

    if use_ml:
        scores = await score_with_ml(
            query, prompt_a, response_a, prompt_b, response_b, prompt_c, response_c
        )
        scorer_used = "ml"
    else:
        scores = await score_with_judge(
            query, prompt_a, response_a, prompt_b, response_b, prompt_c, response_c
        )
        scorer_used = "judge"

    return scores, scorer_used
